const fs = require('node:fs'), path = require('node:path');
const ts = require('../../packages/student-web/node_modules/typescript');
const root = path.resolve(__dirname, '../..');
const source = path.join(root, 'third_party/llm-viz/src');
const target = path.join(root, 'packages/student-web/src/lib/transformer-viz/vendor');
let count = 0;
function walk(dir) {
  for (const item of fs.readdirSync(dir, {withFileTypes:true})) {
    const file = path.join(dir,item.name);
    if(item.isDirectory()) {walk(file);continue;}
    if(!/\.tsx?$/.test(file)) continue;
    const dest=path.join(target,path.relative(source,file)).replace(/\.tsx?$/,'.js');
    const result=ts.transpileModule(fs.readFileSync(file,'utf8'),{fileName:file,compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX,esModuleInterop:true,removeComments:false}});
    fs.mkdirSync(path.dirname(dest),{recursive:true});
    fs.writeFileSync(dest,'// Generated by scripts/transformer-workshop/build-vendor.cjs. Source: third_party/llm-viz.\n'+result.outputText);count++;
  }
}
walk(source);console.log(`Built ${count} upstream engine modules.`);
